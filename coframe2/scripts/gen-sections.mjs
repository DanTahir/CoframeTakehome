// Generates app/sections/generated/*.tsx from the scraped homepage body.
//
// One component per top-level <body> child, plus one per <section> inside the
// .content wrapper, so the page composes in the original document order.
import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { loadAssetMap } from './lib/rewrite.mjs';
import { getBody, topLevelChildren, getAttr, htmlToJsx } from './lib/html.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const RAW = path.join(ROOT, 'scrape', 'raw');
const OUT = path.join(ROOT, 'app', 'sections', 'generated');

const assetMap = await loadAssetMap();
const html = await readFile(path.join(RAW, 'index.html'), 'utf8');
const body = getBody(html);

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });

const nodes = topLevelChildren(body.html);

// Explicit names for the top-level body children, keyed by a matching predicate
// so a source reshuffle produces a loud failure rather than silently wrong names.
const TOP_LEVEL = [
  { name: 'CursorContainer', match: (n) => getAttr(n.attrs, 'id') === 'cursor-container' },
  { name: 'NavSection', match: (n) => getAttr(n.attrs, 'class').includes('nav-wrap') },
  { name: 'HeroSection', match: (n) => getAttr(n.attrs, 'id') === 'hero' },
  { name: 'ContentSections', match: (n) => getAttr(n.attrs, 'class').includes('content cc-homepage'), split: true },
  { name: 'FooterSection', match: (n) => getAttr(n.attrs, 'class').includes('footer-container') },
  { name: 'EmbeddedStylesAndScripts', match: (n) => getAttr(n.attrs, 'class') === '' && n.tag === 'div' },
  { name: 'FloatingCta', match: (n) => getAttr(n.attrs, 'class').includes('floating-cta') },
  { name: 'OrphanCompareCell', match: (n) => getAttr(n.attrs, 'class').includes('compare-grid__cell') },
];

const header = (sourceNote) => `/* eslint-disable */
// AUTO-GENERATED by scripts/gen-sections.mjs from the live coframe.com homepage.
// Source: ${sourceNote}
// Do not edit by hand - re-run \`npm run gen:sections\`.
`;

/** Wraps JSX body into a typed function component module. */
function componentModule(name, jsx, sourceNote) {
  return `${header(sourceNote)}
import type * as React from 'react';

export function ${name}(): React.JSX.Element {
  return (
    <>
${indent(jsx, 6)}
    </>
  );
}

export default ${name};
`;
}

function indent(text, spaces) {
  const pad = ' '.repeat(spaces);
  return text
    .split('\n')
    .map((l) => (l.trim() ? pad + l : l))
    .join('\n');
}

/** Very light pretty-printer: newline before each opening tag at nesting depth. */
function formatJsx(jsx) {
  // Break between adjacent tags to keep lines manageable without altering text nodes.
  return jsx.replace(/></g, '>\n<');
}

const generated = [];
const usedNames = new Set();

function emitName(base) {
  let name = base;
  let i = 2;
  while (usedNames.has(name)) name = `${base}${i++}`;
  usedNames.add(name);
  return name;
}

function sectionNameFor(node, index) {
  const id = getAttr(node.attrs, 'id');
  if (id) {
    const camel = id
      .split(/[^a-zA-Z0-9]+/)
      .filter(Boolean)
      .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
      .join('');
    return `${camel}Section`;
  }
  // The one section without an id is the OpenAI partnership banner.
  const cls = getAttr(node.attrs, 'class');
  if (node.html.includes('coframe-openai-lockup')) return 'BannerSection';
  return `Section${index}`;
}

for (const node of nodes) {
  const spec = TOP_LEVEL.find((s) => s.match(node));
  if (!spec) {
    throw new Error(
      `Unrecognised top-level node <${node.tag} ${node.attrs.slice(0, 120)}>. ` +
        'The source page changed shape - update TOP_LEVEL in gen-sections.mjs.',
    );
  }

  if (!spec.split) {
    const name = emitName(spec.name);
    const jsx = formatJsx(htmlToJsx(node.html, { assetMap }));
    await writeFile(
      path.join(OUT, `${name}.tsx`),
      componentModule(name, jsx, `<${node.tag} ${node.attrs.slice(0, 100)}> (${node.html.length}B)`),
    );
    generated.push({ name, kind: 'top-level', bytes: node.html.length });
    continue;
  }

  // .content wrapper: emit one component per inner <section>, plus a wrapper that
  // reproduces the container element itself.
  const inner = topLevelChildren(node.inner);
  const childNames = [];
  for (let idx = 0; idx < inner.length; idx++) {
    const child = inner[idx];
    const name = emitName(sectionNameFor(child, idx));
    childNames.push(name);
    const jsx = formatJsx(htmlToJsx(child.html, { assetMap }));
    await writeFile(
      path.join(OUT, `${name}.tsx`),
      componentModule(name, jsx, `<${child.tag} ${child.attrs.slice(0, 100)}> (${child.html.length}B)`),
    );
    generated.push({ name, kind: 'content-section', bytes: child.html.length });
  }

  const wrapperName = emitName(spec.name);
  const openTag = /^<[^>]*>/.exec(node.html)[0];
  const openJsx = htmlToJsx(openTag + `</${node.tag}>`, { assetMap }).replace(
    new RegExp(`</${node.tag}>$`),
    '',
  );
  const wrapper = `${header(`<${node.tag} ${node.attrs}> wrapper around ${inner.length} sections`)}
import type * as React from 'react';

${childNames.map((n) => `import { ${n} } from './${n}';`).join('\n')}

export function ${wrapperName}(): React.JSX.Element {
  return (
    ${openJsx}
${childNames.map((n) => `      <${n} />`).join('\n')}
    </${node.tag}>
  );
}

export default ${wrapperName};
`;
  await writeFile(path.join(OUT, `${wrapperName}.tsx`), wrapper);
  generated.push({ name: wrapperName, kind: 'wrapper', children: childNames.length });
}

// Barrel file.
const names = generated.map((g) => g.name);
await writeFile(
  path.join(OUT, 'index.ts'),
  `${header(`${names.length} components`)}
${names.map((n) => `export { ${n} } from './${n}';`).join('\n')}
`,
);

// Body attributes, so layout.tsx can reproduce them exactly.
await writeFile(
  path.join(OUT, 'body-attrs.json'),
  JSON.stringify({ attrs: body.attrs, className: getAttr(body.attrs, 'class') }, null, 2),
);

console.log(`Generated ${generated.length} components into app/sections/generated:`);
for (const g of generated) console.log(`  ${g.kind.padEnd(16)} ${g.name}${g.bytes ? ` (${g.bytes}B)` : ''}${g.children ? ` -> ${g.children} children` : ''}`);
console.log(`\nbody attrs: ${body.attrs}`);
